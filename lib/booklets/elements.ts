/**
 * Where an element sits in the booklet's layout: row 1–7 for the periods and
 * 9–10 for the lanthanide and actinide rows (La and Ac stay in group 3),
 * column 1–18.
 */
export function elementPosition(z: number): { row: number; col: number } {
  if (z === 1) return { row: 1, col: 1 };
  if (z === 2) return { row: 1, col: 18 };
  const blocks: [number, number, number][] = [
    // [first Z, period, first Z of its p-block]
    [3, 2, 5],
    [11, 3, 13],
  ];
  for (const [first, period, pStart] of blocks) {
    if (z < first + 8) return { row: period, col: z < pStart ? z - first + 1 : z - pStart + 13 };
  }
  if (z <= 36) return { row: 4, col: z - 18 };
  if (z <= 54) return { row: 5, col: z - 36 };
  if (z <= 57) return { row: 6, col: z - 54 };
  if (z <= 71) return { row: 9, col: z - 58 + 4 };
  if (z <= 86) return { row: 6, col: z - 68 };
  if (z <= 89) return { row: 7, col: z - 86 };
  if (z <= 103) return { row: 10, col: z - 90 + 4 };
  return { row: 7, col: z - 100 };
}
